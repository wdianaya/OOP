package nsu.oop.wdianaya.task122;

import java.util.Set;

/**
 * Пользовательский интерфейс для хеш-таблицы (ассоциативного массива).
 * Хранит пары «ключ-значение» и предоставляет базовые операции над ними.
 *
 * @param <K> тип ключей, поддерживаемых таблицей
 * @param <V> тип значений, хранящихся в таблице
 */
public interface CustomMap<K, V> {

    /**
     * Добавляет пару ключ-значение в таблицу.
     * Если переданный ключ уже существует, его текущее значение перезаписывается.
     *
     * @param key   ключ, с которым ассоциируется значение
     * @param value значение, которое нужно сохранить
     */
    void addValue(K key, V value);

    /**
     * Удаляет пару ключ-значение, связанную с указанным ключом.
     * Если ключ отсутствует в таблице, ничего не происходит.
     *
     * @param key ключ, который нужно удалить
     */
    void deleteValue(K key);

    /**
     * Возвращает значение, связанное с указанным ключом.
     *
     * @param key ключ, значение которого нужно найти
     * @return значение, связанное с ключом, или {@code null}, если ключ не найден
     */
    V getValue(K key);

    /**
     * Обновляет значение для уже существующего ключа.
     * Если ключа нет в таблице, метод ничего не делает.
     *
     * @param key   ключ, значение которого нужно обновить
     * @param value новое значение
     */
    void updateValue(K key, V value);

    /**
     * Проверяет наличие указанного ключа в таблице.
     *
     * @param key проверяемый ключ
     * @return {@code true}, если ключ присутствует в таблице, иначе {@code false}
     */
    boolean isExistValue(K key);

    /**
     * Возвращает множество всех пар ключ-значение, содержащихся в таблице.
     *
     * @return множество объектов {@link CustomEntry}
     */
    Set<CustomEntry<K, V>> entrySet();

    /**
     * Вспомогательный интерфейс, представляющий собой одну пару «ключ-значение».
     * Используется для итерации по элементам таблицы.
     *
     * @param <K> тип ключа
     * @param <V> тип значения
     */
    interface CustomEntry<K, V> {

        /**
         * Возвращает ключ текущей пары.
         *
         * @return ключ
         */
        K getKey();

        /**
         * Возвращает значение текущей пары.
         *
         * @return значение
         */
        V getValue();
    }
}
