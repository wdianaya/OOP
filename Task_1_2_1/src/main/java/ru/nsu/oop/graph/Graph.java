package ru.nsu.oop.graph;

/**
 * Интерфейс основных операций над графом.
 * Граф считается ориентированным.
 * Методы, работающие с отсутствующей вершиной или ребром,
 * не бросают исключений: они либо ничего не делают,
 * либо возвращают безопасный результат (false, пустой список, 0).
 */
public interface Graph<T> {

    /**
     * Добавляет вершину в граф. Если такая вершина уже есть - ничего не делает.
     *
     * @param value добавляемая вершина
     */
    void addVertex(Vertex<T> value);

    /**
     * Удаляет вершину и все инцидентные ей рёбра.
     * Если вершины нет - ничего не делает.
     *
     * @param value удаляемая вершина
     */
    void delVertex(Vertex<T> value);

    /**
     * Проверяет, есть ли вершина в графе.
     *
     * @param value проверяемая вершина
     * @return true, если вершина есть; false иначе
     */
    boolean hasVertex(Vertex<T> value);

    /**
     * Добавляет ребро. Если вершины ребра отсутствуют - они создаются.
     * Если ребро уже существует - ничего не делает.
     *
     * @param edge добавляемое ребро
     */
    void addEdge(Edge<T> edge);

    /**
     * Удаляет ребро между вершинами. Вершины не удаляются.
     * Если ребра нет - ничего не делает.
     *
     * @param edge удаляемое ребро
     */
    void delEdge(Edge<T> edge);

    /**
     * Проверяет, есть ли ребро между вершинами.
     * Если хотя бы одной из вершин нет - возвращает false.
     *
     * @param edge проверяемое ребро
     * @return true, если ребро есть; false иначе
     */
    boolean hasEdge(Edge<T> edge);

    /**
     * Возвращает количество рёбер в графе.
     *
     * @return число рёбер
     */
    int countEdge();

    /**
     * Возвращает соседей вершины - вершин, соединённых с данной ребром.
     * Соседи уникальны.
     *
     * @param curVertex вершина, для которой ищутся соседи
     * @return соседи вершины; пустой список, если вершины нет
     */
    Iterable<Vertex<T>> getNeighbors(Vertex<T> curVertex);

    /**
     * Возвращает все вершины графа.
     */
    Iterable<Vertex<T>> vertices();
}
